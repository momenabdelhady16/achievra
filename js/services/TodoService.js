/**
 * @typedef {Readonly<{
 *   id: string,
 *   title: string,
 *   description: string,
 *   dueDates: ReadonlyArray<string>,
 *   completed: boolean,
 *   completedAt: string | null
 * }>} Todo
 */

/**
 * @typedef {{
 *   title: string,
 *   description?: string,
 *   dueDates?: string[]
 * }} TodoInput
 */

/**
 * @typedef {{
 *   title?: string,
 *   description?: string,
 *   dueDates?: string[]
 * }} TodoUpdate
 */

/**
 * @typedef {{
 *   addPastDatesAsCompleted?: boolean,
 *   confirmMerge?: boolean,
 *   confirmRepeatedText?: boolean
 * }} TodoDecisions
 */

/**
 * @typedef {{
 *   status: 'created' | 'updated' | 'merged' | 'duplicate' | 'confirmation-required',
 *   todo?: Todo,
 *   existingTodo?: Todo,
 *   proposedInput?: TodoInput,
 *   reason?: 'past-date' | 'merge' | 'repeated-text',
 *   repeatedFragments?: string[],
 *   message?: string
 * }} TodoOperationResult
 */

const TODO_INPUT_FIELDS = Object.freeze(['title', 'description', 'dueDates']);
const TODO_UPDATE_FIELDS = Object.freeze(['title', 'description', 'dueDates']);

const TITLE_ERROR_MESSAGES = Object.freeze({
  [TEXT_VALIDATION_REASONS.INVALID_TYPE]: 'Title must be a string.',
  [TEXT_VALIDATION_REASONS.BLANK_TITLE]: 'Title is required.',
  [TEXT_VALIDATION_REASONS.TOO_SHORT]: 'Title must be at least 1 character.',
  [TEXT_VALIDATION_REASONS.TOO_LONG]: 'Title must be at most 32 characters.',
});

const DESCRIPTION_ERROR_MESSAGES = Object.freeze({
  [TEXT_VALIDATION_REASONS.INVALID_TYPE]: 'Description must be a string.',
  [TEXT_VALIDATION_REASONS.TOO_SHORT]: 'Description is too short.',
  [TEXT_VALIDATION_REASONS.TOO_LONG]: 'Description must be at most 256 characters.',
});

const DUE_DATES_ERROR_MESSAGES = Object.freeze({
  [DATE_VALIDATION_REASONS.INVALID_TYPE]: 'Due dates must be an array of YYYY-MM-DD calendar dates.',
  [DATE_VALIDATION_REASONS.INVALID_FORMAT]: 'Each due date must use YYYY-MM-DD format.',
  [DATE_VALIDATION_REASONS.INVALID_CALENDAR_DATE]: 'Each due date must be a real calendar date.',
  [DATE_VALIDATION_REASONS.DUPLICATE_DATE]: 'Due dates must be unique.',
});

/**
 * @param {unknown} value
 * @returns {boolean}
 */
function isPlainObject(value) {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) {
    return false;
  }
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}

/**
 * Today's calendar date from the current local year, month, and day.
 * @returns {string}
 */
function getTodayCalendarDate() {
  const now = new Date();
  return createCalendarDate(now.getFullYear(), now.getMonth() + 1, now.getDate());
}

/**
 * Current UTC ISO-8601 timestamp for completion metadata.
 * @returns {string}
 */
function getCurrentUtcIsoTimestamp() {
  return new Date().toISOString();
}

/**
 * @param {string | null | undefined} reason
 * @param {Record<string, string>} messages
 * @param {string} fallback
 * @returns {string}
 */
function messageForReason(reason, messages, fallback) {
  if (reason && Object.prototype.hasOwnProperty.call(messages, reason)) {
    return messages[reason];
  }
  return fallback;
}

/**
 * @param {unknown} payload
 * @param {string} argumentName
 * @param {readonly string[]} allowedFields
 * @param {boolean} requireAtLeastOneField
 */
function assertPayloadShape(payload, argumentName, allowedFields, requireAtLeastOneField) {
  if (!isPlainObject(payload)) {
    throw new DomainValidationError(
      argumentName,
      `${argumentName} must be a non-null plain object.`
    );
  }

  if (Object.prototype.hasOwnProperty.call(payload, 'id')) {
    throw new DomainValidationError(
      'id',
      'Task id is generated by the repository and cannot be set or modified.'
    );
  }

  const keys = Object.keys(payload);
  if (requireAtLeastOneField && keys.length === 0) {
    throw new DomainValidationError(
      argumentName,
      `${argumentName} must specify at least one field to update.`
    );
  }

  for (const key of keys) {
    if (!allowedFields.includes(key)) {
      throw new DomainValidationError(
        key,
        `Unknown or disallowed task field "${key}".`
      );
    }
  }
}

/**
 * @param {ReturnType<typeof validateTaskModelInput>} validation
 */
function throwIfInvalidTaskInput(validation) {
  if (validation.valid) {
    return;
  }

  if (!validation.titleResult.valid) {
    throw new DomainValidationError(
      'title',
      messageForReason(
        validation.titleResult.reason,
        TITLE_ERROR_MESSAGES,
        'Title is invalid.'
      )
    );
  }

  if (!validation.descriptionResult.valid) {
    throw new DomainValidationError(
      'description',
      messageForReason(
        validation.descriptionResult.reason,
        DESCRIPTION_ERROR_MESSAGES,
        'Description is invalid.'
      )
    );
  }

  throw new DomainValidationError(
    'dueDates',
    messageForReason(
      validation.dueDatesResult.reason,
      DUE_DATES_ERROR_MESSAGES,
      'Due dates are invalid.'
    )
  );
}

/**
 * @param {unknown} input
 * @returns {Readonly<{ title: string, description: string, dueDates: ReadonlyArray<string> }>}
 */
function normalizeRequiredInput(input) {
  assertPayloadShape(input, 'input', TODO_INPUT_FIELDS, false);
  const validation = validateTaskModelInput({
    title: input.title,
    description: input.description === undefined ? '' : input.description,
    dueDates: input.dueDates === undefined ? [] : input.dueDates,
  });
  throwIfInvalidTaskInput(validation);
  return validation.normalizedInput;
}

/**
 * @param {unknown} decisions
 * @returns {TodoDecisions}
 */
function resolveDecisions(decisions) {
  if (decisions === undefined || decisions === null) {
    return {};
  }
  if (!isPlainObject(decisions)) {
    throw new DomainValidationError(
      'decisions',
      'decisions must be a plain object.'
    );
  }
  return decisions;
}

/**
 * @param {readonly Todo[]} todos
 * @param {string} title
 * @param {string | null} [excludeId]
 * @returns {Todo | null}
 */
function findMatchingPendingTodo(todos, title, excludeId = null) {
  for (const todo of todos) {
    if (todo.completed !== false) {
      continue;
    }
    if (excludeId !== null && todo.id === excludeId) {
      continue;
    }
    if (areTitlesEqual(todo.title, title)) {
      return todo;
    }
  }
  return null;
}

/**
 * @param {readonly string[]} existingDates
 * @param {readonly string[]} proposedDates
 * @returns {boolean}
 */
function areAllProposedDatesPresent(existingDates, proposedDates) {
  const existingSet = new Set(existingDates);
  return proposedDates.every((date) => existingSet.has(date));
}

/**
 * @param {readonly string[]} existingDates
 * @param {readonly string[]} proposedDates
 * @returns {string[]}
 */
function unionDueDates(existingDates, proposedDates) {
  const seen = new Set(existingDates);
  const nextDates = [...existingDates];
  for (const date of proposedDates) {
    if (!seen.has(date)) {
      seen.add(date);
      nextDates.push(date);
    }
  }
  return nextDates;
}

/**
 * @param {string} existingDescription
 * @param {string} incomingDescription
 * @returns {string}
 */
function combineDescriptions(existingDescription, incomingDescription) {
  if (existingDescription.length === 0) {
    return incomingDescription;
  }
  return `${existingDescription}\n${incomingDescription}`;
}

/**
 * @param {string} combinedDescription
 */
function assertCombinedDescriptionLimit(combinedDescription) {
  if (countCharacters(combinedDescription) > DESCRIPTION_MAX_LENGTH) {
    throw new DomainValidationError(
      'description',
      'Merged description must be at most 256 characters, including the separating newline.'
    );
  }
}

/**
 * @param {Todo} existingTodo
 * @param {string} message
 * @returns {TodoOperationResult}
 */
function duplicateResult(existingTodo, message) {
  return {
    status: 'duplicate',
    existingTodo,
    message,
  };
}

/**
 * @param {{
 *   reason: 'past-date' | 'merge' | 'repeated-text',
 *   proposedInput: TodoInput,
 *   message: string,
 *   existingTodo?: Todo,
 *   repeatedFragments?: string[]
 * }} details
 * @returns {TodoOperationResult}
 */
function confirmationRequiredResult(details) {
  const result = {
    status: 'confirmation-required',
    reason: details.reason,
    proposedInput: {
      title: details.proposedInput.title,
      description: details.proposedInput.description,
      dueDates: [...details.proposedInput.dueDates],
    },
    message: details.message,
  };
  if (details.existingTodo) {
    result.existingTodo = details.existingTodo;
  }
  if (details.repeatedFragments) {
    result.repeatedFragments = details.repeatedFragments;
  }
  return result;
}

/**
 * Resolves duplicate / merge rules against one matching Pending Todo.
 *
 * @param {object} params
 * @param {Todo} params.matchingTodo
 * @param {Readonly<{ title: string, description: string, dueDates: ReadonlyArray<string> }>} params.proposedInput
 * @param {TodoDecisions} params.decisions
 * @param {(targetChanges: TodoUpdate) => Promise<Todo>} params.persistMergedTarget
 * @returns {Promise<TodoOperationResult>}
 */
async function resolveDuplicateOrMerge({
  matchingTodo,
  proposedInput,
  decisions,
  persistMergedTarget,
}) {
  if (proposedInput.description.length === 0) {
    return duplicateResult(
      matchingTodo,
      'A pending task with this title already exists.'
    );
  }

  if (areDescriptionsEqual(matchingTodo.description, proposedInput.description)) {
    if (areAllProposedDatesPresent(matchingTodo.dueDates, proposedInput.dueDates)) {
      return duplicateResult(
        matchingTodo,
        'This task already exists.'
      );
    }

    const savedTodo = await persistMergedTarget({
      title: matchingTodo.title,
      description: matchingTodo.description,
      dueDates: unionDueDates(matchingTodo.dueDates, proposedInput.dueDates),
    });
    return { status: 'merged', todo: savedTodo };
  }

  if (decisions.confirmMerge !== true) {
    return confirmationRequiredResult({
      reason: 'merge',
      existingTodo: matchingTodo,
      proposedInput,
      message:
        'A pending task with this title already exists. Confirm to merge the new description and dates into the existing task.',
    });
  }

  const combinedDescription = combineDescriptions(
    matchingTodo.description,
    proposedInput.description
  );
  assertCombinedDescriptionLimit(combinedDescription);

  parseDescriptionSentenceSegments(matchingTodo.description);
  parseDescriptionSentenceSegments(proposedInput.description);
  const repetition = findRepeatedDescriptionSentences(
    matchingTodo.description,
    proposedInput.description
  );
  if (
    repetition.exceedsRepeatedThreshold &&
    decisions.confirmRepeatedText !== true
  ) {
    return confirmationRequiredResult({
      reason: 'repeated-text',
      existingTodo: matchingTodo,
      proposedInput,
      repeatedFragments: repetition.repeatedSegments.map(
        (segment) => segment.displaySegment
      ),
      message:
        'The descriptions share repeated text. Confirm to merge them anyway.',
    });
  }

  const savedTodo = await persistMergedTarget({
    title: matchingTodo.title,
    description: combinedDescription,
    dueDates: unionDueDates(matchingTodo.dueDates, proposedInput.dueDates),
  });
  return { status: 'merged', todo: savedTodo };
}

/**
 * @param {unknown} error
 * @returns {'validation' | 'storage'}
 */
function failureKindForError(error) {
  if (error instanceof DomainValidationError) {
    return 'validation';
  }
  if (error instanceof StorageError) {
    return 'storage';
  }
  throw error;
}

export class TodoService {
  /**
   * @param {import('../repositories/TodoRepository.js').TodoRepository} repository
   */
  constructor(repository, operationLog = null) {
    if (repository === null || repository === undefined || typeof repository !== 'object') {
      throw new TypeError('TodoService requires a TodoRepository instance.');
    }
    this.repository = repository;
    this.operationLog = operationLog;
    this.#mutationQueue = Promise.resolve();
  }

  #mutationQueue;

  #enqueueMutation(operation) {
    const result = this.#mutationQueue.then(operation);
    this.#mutationQueue = result.then(() => undefined, () => undefined);
    return result;
  }

  async #persistMutation(operationType, persist) {
    if (!this.operationLog) return persist(undefined);
    let operationId = null;
    let journalAttempted = false;
    let expectedAfter = [];
    const beforePersist = async (details) => {
      // If the journal itself cannot accept the write-ahead record, do not try
      // to append a second failure record from the caller.
      journalAttempted = true;
      expectedAfter = (details.afterTodos ?? []).map((todo) => ({ ...todo, dueDates: [...todo.dueDates] }));
      operationId = await this.operationLog.recordBeforePersist({
        ...details,
        operationType: details.operationType ?? operationType,
      });
    };
    try {
      const result = await persist(beforePersist);
      if (operationId) {
        try { await this.operationLog.markCommitted(operationId, expectedAfter); } catch { /* The prepared entry is reconciled on the next check. */ }
      }
      return result;
    } catch (error) {
      if (operationId) {
        try { await this.operationLog.markFailed(operationId, error); } catch { /* Keep the original persistence error. */ }
      }
      if (journalAttempted && error && typeof error === 'object') error.operationLogRecorded = true;
      throw error;
    }
  }

  async #recordUnjournaledFailure(operationType, input, error, taskId = null) {
    if (!this.operationLog || error?.operationLogRecorded) return;
    try {
      await this.operationLog.recordPrePersistFailure({ operationType, input, taskId, error });
    } catch (logError) {
      // Validation still rejects; attach journal failure so diagnostics retain both causes.
      if (error && typeof error === 'object') error.operationLogError = logError;
    }
  }

  async #recordNonPersistedResult(operationType, result, input = {}) {
    if (!this.operationLog || !['duplicate', 'confirmation-required'].includes(result?.status)) return;
    try {
      await this.operationLog.recordNonPersistedOutcome({
        operationType,
        status: result.status,
        input: result.proposedInput ?? input,
        existingTodo: result.existingTodo ?? null,
        reason: result.reason ?? null,
        message: result.message ?? '',
      });
    } catch (error) {
      result.operationLogError = error;
    }
  }

  /**
   * Loads all Todos once, partitions by `completed`, and sorts each section.
   *
   * @returns {Promise<{ pendingTodos: Todo[], completedTodos: Todo[] }>}
   */
  async getTaskLists() {
    const todos = await this.repository.getAll();
    const grouped = sortTasksByExplicitGroup(todos, getTodayCalendarDate());
    return {
      pendingTodos: grouped.pending,
      completedTodos: grouped.completed,
    };
  }

  /**
   * @returns {Promise<Todo[]>}
   */
  async getPendingTodos() {
    const { pendingTodos } = await this.getTaskLists();
    return pendingTodos;
  }

  /**
   * @returns {Promise<Todo[]>}
   */
  async getCompletedTodos() {
    const { completedTodos } = await this.getTaskLists();
    return completedTodos;
  }

  /** Idempotently restore a validated Todo snapshot during journal recovery. */
  async restoreTodoSnapshot(todoSnapshot) {
    if (typeof this.repository.restoreTodoSnapshot !== 'function') {
      throw new StorageError('The configured TodoRepository does not support operation recovery.');
    }
    return this.#persistMutation('recovery', (beforePersist) =>
      this.repository.restoreTodoSnapshot(todoSnapshot, { beforePersist, operationType: 'recovery' }));
  }

  /** Replay an atomic merge recorded before an interrupted repository write. */
  async recoverMerge(sourceId, targetId, targetTodo) {
    if (typeof this.repository.merge !== 'function') {
      throw new StorageError('The configured TodoRepository does not support merge recovery.');
    }
    return this.#persistMutation('recovery', (beforePersist) => this.repository.merge(sourceId, targetId, {
      title: targetTodo.title,
      description: targetTodo.description,
      dueDates: [...targetTodo.dueDates],
      completed: targetTodo.completed,
      completedAt: targetTodo.completedAt,
    }, { beforePersist, operationType: 'recovery' }));
  }

  /**
   * @param {{ title?: unknown, description?: unknown, dueDates?: unknown }} input
   * @returns {{ valid: boolean, errors: Record<string, string> }}
   */
  validateTaskInput({ title, description, dueDates } = {}) {
    const validation = validateTaskModelInput({
      title,
      description: description === undefined ? '' : description,
      dueDates: dueDates === undefined ? [] : dueDates,
    });

    /** @type {Record<string, string>} */
    const errors = {};
    if (!validation.titleResult.valid) {
      errors.title = messageForReason(
        validation.titleResult.reason,
        TITLE_ERROR_MESSAGES,
        'Title is invalid.'
      );
    }
    if (!validation.descriptionResult.valid) {
      errors.description = messageForReason(
        validation.descriptionResult.reason,
        DESCRIPTION_ERROR_MESSAGES,
        'Description is invalid.'
      );
    }
    if (!validation.dueDatesResult.valid) {
      errors.dueDates = messageForReason(
        validation.dueDatesResult.reason,
        DUE_DATES_ERROR_MESSAGES,
        'Due dates are invalid.'
      );
    }

    return {
      valid: validation.valid,
      errors,
    };
  }

  /**
   * @param {TodoInput} input
   * @param {TodoDecisions} [decisions]
   * @returns {Promise<TodoOperationResult>}
   */
  createTodo(input, decisions = {}) {
    return this.#enqueueMutation(async () => {
      try {
        const result = await this.#createTodo(input, decisions);
        await this.#recordNonPersistedResult('create', result, input ?? {});
        return result;
      } catch (error) {
        await this.#recordUnjournaledFailure('create', input ?? {}, error);
        throw error;
      }
    });
  }

  async #createTodo(input, decisions = {}) {
    const resolvedDecisions = resolveDecisions(decisions);
    const normalizedInput = normalizeRequiredInput(input);
    const proposedInput = {
      title: normalizedInput.title,
      description: normalizedInput.description,
      dueDates: [...normalizedInput.dueDates],
    };

    const todayDate = getTodayCalendarDate();
    const pastDates = findPastDueDates(proposedInput.dueDates, todayDate);
    if (pastDates.length > 0) {
      if (resolvedDecisions.addPastDatesAsCompleted !== true) {
        return confirmationRequiredResult({
          reason: 'past-date',
          proposedInput,
          message:
            'This due date has already passed. Would you like to add this task as Completed?',
        });
      }

      const todo = await this.#persistMutation('create', (beforePersist) => this.repository.create({
        title: proposedInput.title,
        description: proposedInput.description,
        dueDates: proposedInput.dueDates,
        completed: true,
        completedAt: getCurrentUtcIsoTimestamp(),
      }, { beforePersist }));
      return { status: 'created', todo };
    }

    const todos = await this.repository.getAll();
    const matchingTodo = findMatchingPendingTodo(todos, proposedInput.title);
    if (!matchingTodo) {
      const todo = await this.#persistMutation('create', (beforePersist) => this.repository.create({
        title: proposedInput.title,
        description: proposedInput.description,
        dueDates: proposedInput.dueDates,
        completed: false,
        completedAt: null,
      }, { beforePersist }));
      return { status: 'created', todo };
    }

    return resolveDuplicateOrMerge({
      matchingTodo,
      proposedInput,
      decisions: resolvedDecisions,
      persistMergedTarget: (targetChanges) =>
        this.#persistMutation('merge', (beforePersist) =>
          this.repository.update(matchingTodo.id, targetChanges, { beforePersist, operationType: 'merge' })),
    });
  }

  /**
   * Confirmed create-merge into an existing Pending Todo.
   * Returns the saved Todo, or a confirmation-required result when repeated-text
   * confirmation is still missing.
   *
   * @param {string} existingId
   * @param {string} newDescription
   * @param {readonly string[] | undefined} dueDates
   * @param {TodoDecisions} [decisions]
   * @returns {Promise<Todo | TodoOperationResult>}
   */
  confirmMerge(existingId, newDescription, dueDates = [], decisions = {}) {
    return this.#enqueueMutation(async () => {
      const result = await this.#confirmMerge(existingId, newDescription, dueDates, decisions);
      if (result?.status) {
        await this.#recordNonPersistedResult('merge', result, {
          title: result.existingTodo?.title ?? '', description: newDescription, dueDates,
        });
      }
      return result;
    });
  }

  async #confirmMerge(existingId, newDescription, dueDates = [], decisions = {}) {
    if (typeof existingId !== 'string' || existingId.trim().length === 0) {
      throw new DomainValidationError(
        'existingId',
        'existingId must be a non-empty string.'
      );
    }

    const resolvedDecisions = resolveDecisions(decisions);
    const descriptionValidation = validateTaskModelInput({
      title: 'placeholder',
      description: newDescription,
      dueDates: dueDates === undefined ? [] : dueDates,
    });
    if (!descriptionValidation.descriptionResult.valid) {
      throw new DomainValidationError(
        'description',
        messageForReason(
          descriptionValidation.descriptionResult.reason,
          DESCRIPTION_ERROR_MESSAGES,
          'Description is invalid.'
        )
      );
    }
    if (!descriptionValidation.dueDatesResult.valid) {
      throw new DomainValidationError(
        'dueDates',
        messageForReason(
          descriptionValidation.dueDatesResult.reason,
          DUE_DATES_ERROR_MESSAGES,
          'Due dates are invalid.'
        )
      );
    }

    const todos = await this.repository.getAll();
    const matchingTodo = todos.find((todo) => todo.id === existingId);
    if (!matchingTodo) {
      throw new DomainValidationError(
        'existingId',
        `Task with id "${existingId}" does not exist.`
      );
    }
    if (matchingTodo.completed !== false) {
      throw new DomainValidationError(
        'existingId',
        'Only a pending task can receive a merge.'
      );
    }

    const proposedInput = {
      title: matchingTodo.title,
      description: descriptionValidation.normalizedInput.description,
      dueDates: [...descriptionValidation.normalizedInput.dueDates],
    };

    const result = await resolveDuplicateOrMerge({
      matchingTodo,
      proposedInput,
      decisions: {
        ...resolvedDecisions,
        confirmMerge: true,
      },
      persistMergedTarget: (targetChanges) =>
        this.#persistMutation('merge', (beforePersist) =>
          this.repository.update(existingId, targetChanges, { beforePersist, operationType: 'merge' })),
    });

    if (result.status === 'merged') {
      return result.todo;
    }
    return result;
  }

  /**
   * @param {string} id
   * @param {TodoUpdate} changes
   * @param {TodoDecisions} [decisions]
   * @returns {Promise<TodoOperationResult>}
   */
  updatePendingTodo(id, changes, decisions = {}) {
    return this.#enqueueMutation(async () => {
      try {
        const result = await this.#updatePendingTodo(id, changes, decisions);
        await this.#recordNonPersistedResult('update', result, changes ?? {});
        return result;
      } catch (error) {
        await this.#recordUnjournaledFailure('update', changes ?? {}, error, id);
        throw error;
      }
    });
  }

  async #updatePendingTodo(id, changes, decisions = {}) {
    if (typeof id !== 'string' || id.trim().length === 0) {
      throw new DomainValidationError('id', 'Task id must be a non-empty string.');
    }

    assertPayloadShape(changes, 'changes', TODO_UPDATE_FIELDS, true);
    const resolvedDecisions = resolveDecisions(decisions);

    const todos = await this.repository.getAll();
    const existingTodo = todos.find((todo) => todo.id === id);
    if (!existingTodo) {
      throw new DomainValidationError('id', `Task with id "${id}" does not exist.`);
    }
    if (existingTodo.completed !== false) {
      throw new DomainValidationError(
        'id',
        'Completed tasks cannot be edited.'
      );
    }

    const nextTitle =
      Object.prototype.hasOwnProperty.call(changes, 'title')
        ? changes.title
        : existingTodo.title;
    const nextDescription =
      Object.prototype.hasOwnProperty.call(changes, 'description')
        ? changes.description
        : existingTodo.description;
    const nextDueDates =
      Object.prototype.hasOwnProperty.call(changes, 'dueDates')
        ? changes.dueDates
        : existingTodo.dueDates;

    const validation = validateTaskModelInput({
      title: nextTitle,
      description: nextDescription,
      dueDates: nextDueDates,
    });
    throwIfInvalidTaskInput(validation);

    const proposedInput = {
      title: validation.normalizedInput.title,
      description: validation.normalizedInput.description,
      dueDates: [...validation.normalizedInput.dueDates],
    };

    if (Object.prototype.hasOwnProperty.call(changes, 'dueDates')) {
      const todayDate = getTodayCalendarDate();
      const existingDateSet = new Set(existingTodo.dueDates);
      const addedPastDates = findPastDueDates(
        proposedInput.dueDates.filter((date) => !existingDateSet.has(date)),
        todayDate
      );
      if (addedPastDates.length > 0) {
        throw new DomainValidationError(
          'dueDates',
          'A pending task cannot add or set a new past due date.'
        );
      }
    }

    const matchingTodo = findMatchingPendingTodo(
      todos,
      proposedInput.title,
      existingTodo.id
    );
    if (!matchingTodo) {
      const persistedChanges = {};
      if (Object.prototype.hasOwnProperty.call(changes, 'title')) {
        persistedChanges.title = proposedInput.title;
      }
      if (Object.prototype.hasOwnProperty.call(changes, 'description')) {
        persistedChanges.description = proposedInput.description;
      }
      if (Object.prototype.hasOwnProperty.call(changes, 'dueDates')) {
        persistedChanges.dueDates = proposedInput.dueDates;
      }

      const todo = await this.#persistMutation('update', (beforePersist) =>
        this.repository.update(id, persistedChanges, { beforePersist, operationType: 'update' }));
      return { status: 'updated', todo };
    }

    return resolveDuplicateOrMerge({
      matchingTodo,
      proposedInput,
      decisions: resolvedDecisions,
      persistMergedTarget: (targetChanges) =>
        this.#persistMutation('merge', (beforePersist) =>
          this.repository.merge(existingTodo.id, matchingTodo.id, targetChanges, { beforePersist })),
    });
  }

  /**
   * @param {readonly string[]} ids
   * @returns {Promise<{
   *   completed: Todo[],
   *   failures: Array<{ id: string, kind: 'validation' | 'storage', message: string }>
   * }>}
   */
  async completeTodos(ids) {
    if (!Array.isArray(ids)) {
      throw new DomainValidationError(
        'ids',
        'ids must be an array of task IDs.'
      );
    }

    const todos = await this.repository.getAll();
    const todosById = new Map(todos.map((todo) => [todo.id, todo]));
    const completed = [];
    const failures = [];

    for (const rawId of ids) {
      if (typeof rawId !== 'string' || rawId.trim().length === 0) {
        failures.push({
          id: String(rawId),
          kind: 'validation',
          message: 'Task ID must be a non-empty string.',
        });
        continue;
      }

      const existingTodo = todosById.get(rawId);
      if (!existingTodo) {
        failures.push({
          id: rawId,
          kind: 'validation',
          message: `Task with id "${rawId}" was not found.`,
        });
        continue;
      }

      if (existingTodo.completed === true) {
        failures.push({
          id: rawId,
          kind: 'validation',
          message: 'Completed tasks cannot be completed again.',
        });
        continue;
      }

      try {
        const savedTodo = await this.#persistMutation('complete', (beforePersist) =>
          this.repository.update(rawId, {
            completed: true,
            completedAt: getCurrentUtcIsoTimestamp(),
          }, { beforePersist, operationType: 'complete' }));
        todosById.set(rawId, savedTodo);
        completed.push(savedTodo);
      } catch (error) {
        await this.#recordUnjournaledFailure('complete', {}, error, rawId);
        failures.push({
          id: rawId,
          kind: failureKindForError(error),
          message: error.message,
        });
      }
    }

    return { completed, failures };
  }

  /**
   * Commits deletion after the caller’s grace period has expired.
   *
   * @param {readonly string[]} ids
   * @returns {Promise<{
   *   deletedIds: string[],
   *   failures: Array<{ id: string, kind: 'validation' | 'storage', message: string }>
   * }>}
   */
  async commitDelete(ids, operationIdByTaskId = {}) {
    if (!Array.isArray(ids)) {
      throw new DomainValidationError(
        'ids',
        'ids must be an array of task IDs.'
      );
    }

    const operationIds = { ...operationIdByTaskId };
    try {
      for (const operationId of Object.values(operationIds)) {
        if (operationId) await this.operationLog?.markCommitRequested(operationId);
      }
      const result = await this.repository.deleteMany(ids, {
        operationIdByTaskId: operationIds,
        beforePersist: async ({ beforeTodos }) => {
          if (!this.operationLog) return;
          for (const todo of beforeTodos) {
            if (!operationIds[todo.id]) {
              operationIds[todo.id] = await this.operationLog.recordBeforePersist({
                operationType: 'delete', beforeTodos: [todo], afterTodos: [],
              });
            }
          }
        },
      });
      for (const id of result.deletedIds) {
        if (operationIds[id]) {
          try { await this.operationLog?.markCommitted(operationIds[id], []); } catch { /* Pending journal entries are reconciled later. */ }
        }
      }
      for (const failure of result.failures) {
        if (operationIds[failure.id]) {
          try { await this.operationLog?.markFailed(operationIds[failure.id], new Error(failure.message)); } catch { /* Preserve per-item result. */ }
        }
      }
      return {
        deletedIds: [...result.deletedIds],
        failures: result.failures.map((failure) => ({
          id: failure.id,
          kind: 'validation',
          message: failure.message,
        })),
      };
    } catch (error) {
      if (error instanceof StorageError) {
        for (const operationId of Object.values(operationIds)) {
          if (operationId) {
            try { await this.operationLog?.markFailed(operationId, error); } catch { /* The unresolved entry is retained for recovery. */ }
          }
        }
        return {
          deletedIds: [],
          failures: ids.map((id) => ({
            id: typeof id === 'string' ? id : String(id),
            kind: 'storage',
            message: error.message,
          })),
        };
      }
      throw error;
    }
  }
}

export default TodoService;
